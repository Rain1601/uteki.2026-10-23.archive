ALIASES = ('opus55', 'fable51')
DOCUMENTS = ('context-request.md', 'system.txt', 'codex-baseline.md', 'pricing.json')
ENDPOINT = 'https://aihubmix.com/v1/messages'
MAX_TOKENS = 16000
TIMEOUT = 300
LIMIT = '2'
SAFE_ID = re.compile(r'[A-Za-z0-9][A-Za-z0-9._:/-]{0,255}\Z')


def utc_now():
    return datetime.now(timezone.utc).isoformat()


def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True,
                      separators=(',', ':'), allow_nan=False).encode('utf-8')


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def file_hash(path):
    path = Path(path)
    if path.is_symlink() or not path.is_file():
        raise ValueError('A regular, non-symlink source file is required')
    return digest(path.read_bytes())


def read_json(path):
    return json.loads(Path(path).read_bytes(), parse_constant=lambda _: (_ for _ in ()).throw(ValueError('Nonfinite JSON')))


def write_json(path, value, *, exclusive=False, key=''):
    text = json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + '\n'
    if key:
        text = text.replace(key, '[REDACTED]')
    with Path(path).open('x' if exclusive else 'w', encoding='utf-8') as stream:
        stream.write(text)


@contextmanager
def locked(base):
    base.mkdir(parents=True, exist_ok=True)
    with (base / '.consult.lock').open('a') as stream:
        try:
            fcntl.flock(stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            raise ValueError('Another preparation or dispatch is active') from None
        try:
            yield
        finally:
            fcntl.flock(stream, fcntl.LOCK_UN)


def prices(path):
    value = read_json(path)
    if not isinstance(value, dict) or set(value) != set(ALIASES):
        raise ValueError('Exactly two explicit price/model selections are required')
    for alias, price in value.items():
        if not isinstance(price, dict) or set(price) != {'model', 'input_per_million',
                'output_per_million', 'cache_read_per_million', 'source_url', 'checked_date'}:
            raise ValueError('Incomplete price evidence')
        if not isinstance(price['model'], str) or not SAFE_ID.fullmatch(price['model']):
            raise ValueError('Explicit provider model identifier required')
        for field in ('input_per_million', 'output_per_million', 'cache_read_per_million'):
            amount = Decimal(str(price[field]))
            if not amount.is_finite() or amount < 0:
                raise ValueError('Invalid price')
        if not isinstance(price['source_url'], str) or not price['source_url'].startswith('https://'):
            raise ValueError('Price source URL required')
        if not isinstance(price['checked_date'], str) or not re.fullmatch(r'\d{4}-\d{2}-\d{2}', price['checked_date']):
            raise ValueError('Price verification date required')
    if value['opus55']['model'] == value['fable51']['model']:
        raise ValueError('Distinct explicitly selected models required')
    return value


def runtime_evidence():
    """Pin interpreter and installed HTTP stack files, excluding generated bytecode."""
    evidence = {'python_version': sys.version, 'python_executable': str(Path(sys.executable).resolve()),
                'python_sha256': file_hash(Path(sys.executable).resolve()), 'distributions': {}}
    packages = ['httpx2', 'httpcore2', 'anyio', 'idna', 'truststore', 'h11', 'typing_extensions', 'sniffio']
    # HTTP response decoders can be discovered automatically by the client.
    for optional in ('brotli', 'brotlicffi', 'backports-zstd', 'zstandard'):
        try:
            importlib.metadata.distribution(optional)
        except importlib.metadata.PackageNotFoundError:
            continue
        packages.append(optional)
    for name in packages:
        dist = importlib.metadata.distribution(name)
        files = {}
        for item in dist.files or []:
            if '__pycache__' in item.parts or item.suffix == '.pyc':
                continue
            path = Path(dist.locate_file(item)).resolve()
            if path.is_file():
                files[str(path)] = file_hash(path)
        if not files:
            raise ValueError('Runtime distribution has no auditable files')
        evidence['distributions'][name] = {'version': dist.version, 'files': files}
    return evidence


def request_for(model, context, system):
    return {'model': model, 'system': system, 'messages': [{'role': 'user', 'content': context}],
            'thinking': {'type': 'adaptive'}, 'output_config': {'effort': 'high'},
            'max_tokens': MAX_TOKENS, 'stream': False}


def configuration(body):
    return build_configuration_snapshot(
        {'provider': 'aihubmix', 'model': body['model'], 'api_format': 'anthropic_messages',
         'base_url': 'https://aihubmix.com', 'max_tokens': MAX_TOKENS,
         'thinking': {'type': 'adaptive'}, 'reasoning_effort': 'high', 'stream': False,
         'timeout_seconds': TIMEOUT, 'max_retries': 0},
        capture_kind='before_dispatch', capture_layer='http_request_before_dispatch',
        source='http_request', statuses={field: 'not_sent' for field in
            ('temperature', 'top_p', 'top_k', 'seed', 'response_format', 'tool_choice', 'parallel_tool_calls')},
        fingerprints={'system_sha256': digest(body['system'].encode('utf-8')),
                      'input_sha256': digest(canonical(body['messages'])), 'tools_sha256': digest(canonical([]))})


def reservation_amount(raw, price):
    return (Decimal(len(raw) + 16000) * Decimal(str(price['input_per_million']))
            + Decimal(MAX_TOKENS) * Decimal(str(price['output_per_million']))) / Decimal(1000000)


def prepare(base=BASE, sources=()):
    base = Path(base)
    with locked(base):
        if (base / 'runs').exists() or (base / 'budget.sqlite').exists():
            raise ValueError('Preparation is frozen once any dispatch attempt is recorded')
        price = prices(base / 'pricing.json')
        prepared = base / 'prepared'
        prepared.mkdir(exist_ok=True)
        hashes = {}
        source_paths = [base / name for name in DOCUMENTS] + [Path(__file__)]
        source_paths += [ROOT / 'src/uteki/agents/runtime' / name for name in
                         ('model_configuration.py', 'run_budget.py', 'local_credentials.py')]
        source_paths += [ROOT / name for name in ('src/uteki/__init__.py',
                         'src/uteki/agents/__init__.py', 'src/uteki/agents/runtime/__init__.py')]
        source_paths += [Path(path).resolve() for path in sources]
        for path in source_paths:
            hashes[str(path.resolve())] = file_hash(path)
        for name in DOCUMENTS:
            (prepared / name).write_bytes((base / name).read_bytes())
        context = (prepared / 'context-request.md').read_text(encoding='utf-8')
        system = (prepared / 'system.txt').read_text(encoding='utf-8')
        if not context.strip() or not system.strip():
            raise ValueError('Nonempty complete context and system are required')
        requests = {}
        total = Decimal(0)
        for alias in ALIASES:
            body = request_for(price[alias]['model'], context, system)
            raw = canonical(body)
            (prepared / f'{alias}-request.json').write_bytes(raw)
            snapshot = configuration(body)
            write_json(prepared / f'{alias}-configuration.json', snapshot)
            amount = reservation_amount(raw, price[alias])
            total += amount
            requests[alias] = {'model': body['model'], 'request_sha256': digest(raw),
                               'configuration_sha256': snapshot['sha256'],
                               'request_bytes': len(raw), 'reservation_usd': str(amount)}
        if total > Decimal(LIMIT):
            raise BudgetExceeded('Both conservative reservations exceed the total authorized budget')
        prepared_hashes = {path.name: file_hash(path) for path in prepared.iterdir() if path.is_file()}
        inspection = {'schema_version': 'data-agent-consultation-inspection-v1',
            'provider': 'aihubmix', 'endpoint': ENDPOINT, 'requests': requests,
            'budget_limit_usd': LIMIT, 'both_reservations_usd': str(total),
            'max_tokens': MAX_TOKENS, 'thinking': 'adaptive', 'effort': 'high',
            'timeout_seconds': TIMEOUT, 'max_retries': 0, 'stream': False,
            'tools': 'not_sent', 'sampling_seed_cache_controls': 'not_sent',
            'dispatch_order': list(ALIASES), 'calls_per_model': 1,
            'cost_note': 'Public-price estimate; not an account bill or provider-enforced hard cap.',
            'model_note': 'Requested identifiers and provider-returned model strings do not verify model weights.',
            'preservation': 'Visible text only; hidden thinking and opaque signature/redacted-thinking blocks are omitted.'}
        write_json(base / 'inspection.json', inspection)
        manifest = {'schema_version': 'data-agent-consultation-manifest-v1', 'prepared_at': utc_now(),
                    'source_sha256': hashes, 'prepared_sha256': prepared_hashes,
                    'inspection_sha256': file_hash(base / 'inspection.json'),
                    'runtime': runtime_evidence(), 'requests': requests}
        write_json(base / 'manifest.json', manifest)
        (base / 'manifest.sha256').write_text(file_hash(base / 'manifest.json') + '\n')
        return {'status': 'prepared', 'requests': requests, 'budget_limit_usd': LIMIT,
                'both_reservations_usd': str(total), 'model_calls': 0}


def verify(base):
    expected = (base / 'manifest.sha256').read_text().strip()
    if file_hash(base / 'manifest.json') != expected:
        raise ValueError('Manifest changed')
    manifest = read_json(base / 'manifest.json')
    for name, expected_hash in manifest['source_sha256'].items():
        if file_hash(name) != expected_hash:
            raise ValueError('Pinned source changed')
    for name, expected_hash in manifest['prepared_sha256'].items():
        if Path(name).name != name or file_hash(base / 'prepared' / name) != expected_hash:
            raise ValueError('Frozen prepared file changed')
    if file_hash(base / 'inspection.json') != manifest['inspection_sha256']:
        raise ValueError('Inspection changed')
    if runtime_evidence() != manifest['runtime']:
        raise ValueError('Pinned runtime changed')
    price = prices(base / 'prepared/pricing.json')
    context = (base / 'prepared/context-request.md').read_text(encoding='utf-8')
    system = (base / 'prepared/system.txt').read_text(encoding='utf-8')
    for alias in ALIASES:
        body = read_json(base / 'prepared' / f'{alias}-request.json')
        if body != request_for(price[alias]['model'], context, system):
            raise ValueError('Request does not match frozen context and controls')
        snapshot = validate_configuration_snapshot(read_json(base / 'prepared' / f'{alias}-configuration.json'))
        if snapshot != configuration(body):
            raise ValueError('Configuration does not match request')
    return manifest, price


def identifier(value):
    return value if isinstance(value, str) and SAFE_ID.fullmatch(value) else None


def numeric_usage(raw):
    """Retain exact safe numeric counters; never copy arbitrary provider objects."""
    if not isinstance(raw, dict):
        return None
    result = {}
    for name, value in raw.items():
        if not isinstance(name, str) or not re.fullmatch(r'[a-z][a-z0-9_]{0,79}', name):
            continue
        if type(value) is int and value >= 0:
            result[name] = value
        elif isinstance(value, dict):
            nested = numeric_usage(value)
            if nested:
                result[name] = nested
    return result


def usage_cost(raw, price):
    if not isinstance(raw, dict):
        return None, 'usage_missing'
    for name in ('input_tokens', 'output_tokens'):
        if type(raw.get(name)) is not int or raw[name] < 0:
            return None, 'required_usage_missing_or_invalid'
    for name in ('cache_read_input_tokens', 'cache_creation_input_tokens'):
        if name in raw and (type(raw[name]) is not int or raw[name] < 0):
            return None, 'cache_usage_invalid'
    if raw.get('cache_creation_input_tokens', 0) != 0:
        return None, 'cache_write_price_unknown'
    nested = raw.get('cache_creation')
    if nested is not None and (not isinstance(nested, dict)
            or any(type(value) is not int or value != 0 for value in nested.values())):
        return None, 'cache_write_price_unknown'
    for name, value in raw.items():
        if 'cache' in name and ('write' in name or 'creation' in name) and name not in {
                'cache_creation', 'cache_creation_input_tokens'} and value not in (0, None):
            return None, 'cache_write_price_unknown'
    amount = (Decimal(raw['input_tokens']) * Decimal(str(price['input_per_million']))
              + Decimal(raw['output_tokens']) * Decimal(str(price['output_per_million']))
              + Decimal(raw.get('cache_read_input_tokens', 0)) * Decimal(str(price['cache_read_per_million']))) / 1000000
    return str(amount), 'known_public_price_estimate'


async def run(alias, base=BASE, *, client_factory=httpx.AsyncClient, key_loader=load_provider_key):
    base = Path(base)
    if alias not in ALIASES:
        raise ValueError('Explicit supported consultation selection required')
    with locked(base):
        manifest, price = verify(base)
        if alias == 'fable51':
            prior = base / 'runs/opus55/receipt.json'
            if not prior.exists() or read_json(prior).get('status') != 'completed':
                raise ValueError('Opus must complete with known usage before Fable dispatch')
        output = base / 'runs' / alias
        output.mkdir(parents=True, exist_ok=False)
        raw = (base / 'prepared' / f'{alias}-request.json').read_bytes()
        request = json.loads(raw)
        key = ''
        budget = RunBudget(base / 'budget.sqlite', LIMIT)
        token = None
        sent = settled = False
        started = time.monotonic()
        record = {'schema_version': 'data-agent-consultation-receipt-v1', 'status': 'started',
            'provider': 'aihubmix', 'requested_model': request['model'], 'selection': alias,
            'manifest_sha256': file_hash(base / 'manifest.json'), 'request_sha256': digest(raw),
            'configuration_sha256': manifest['requests'][alias]['configuration_sha256'],
            'runner_sha256': file_hash(Path(__file__)), 'started_at': utc_now(), 'ended_at': None,
            'http_status': None, 'response_id': None, 'returned_model': None, 'stop_reason': None,
            'request_id': None, 'raw_usage': None, 'estimated_usd': None, 'actual_billed_usd': None,
            'model_identity_note': 'Provider claim only; actual model weights are not independently verified.',
            'content_block_types': [], 'omissions': 'All non-text content, hidden thinking, and opaque signing blocks are omitted.'}
        try:
            amount = reservation_amount(raw, price[alias])
            token = budget.reserve(amount)
            record.update(reservation_id=token, reserved_usd=str(amount))
            write_json(output / 'start.json', record, exclusive=True)
            key_loader(ROOT, 'aihubmix')
            key = os.environ[PROVIDER_KEYS['aihubmix']]
            if not key:
                raise ValueError('Credential unavailable')
            headers = {'x-api-key': key, 'anthropic-version': '2023-06-01', 'content-type': 'application/json'}
            previous_logging = logging.root.manager.disable
            logging.disable(logging.CRITICAL)
            try:
                async with client_factory(timeout=TIMEOUT, follow_redirects=False,
                                          transport=httpx.AsyncHTTPTransport(retries=0), trust_env=False) as client:
                    sent = True
                    response = await asyncio.wait_for(client.post(ENDPOINT, content=raw, headers=headers), TIMEOUT)
            finally:
                logging.disable(previous_logging)
            record['http_status'] = response.status_code
            record['request_id'] = identifier(response.headers.get('request-id') or response.headers.get('x-request-id'))
            if response.status_code != 200:
                record.update(status='failed', error_type='HTTPStatusError', error_classification='non_200_response')
            else:
                payload = response.json()
                if not isinstance(payload, dict):
                    raise ValueError('Invalid provider response')
                record.update(response_id=identifier(payload.get('id')), returned_model=identifier(payload.get('model')),
                              stop_reason=identifier(payload.get('stop_reason')), raw_usage=numeric_usage(payload.get('usage')))
                blocks = payload.get('content')
                if not isinstance(blocks, list):
                    raise ValueError('Invalid response content')
                record['content_block_types'] = [identifier(block.get('type')) if isinstance(block, dict) else None for block in blocks]
                visible = ''.join(block['text'] for block in blocks if isinstance(block, dict)
                                  and block.get('type') == 'text' and isinstance(block.get('text'), str))
                record['visible_text_secret_redacted'] = key in visible
                (output / 'answer.md').write_text(visible.replace(key, '[REDACTED]'), encoding='utf-8')
                cost, cost_status = usage_cost(payload.get('usage'), price[alias])
                record.update(estimated_usd=cost, usage_status=cost_status)
                budget.settle(token, cost)
                settled = True
                record['status'] = ('completed' if cost is not None and record['stop_reason'] == 'end_turn'
                                    and visible.strip() else 'incomplete')
                if cost is None:
                    record['error_classification'] = 'usage_or_cost_unknown'
                elif record['stop_reason'] != 'end_turn':
                    record['error_classification'] = 'unexpected_stop_reason'
                elif not visible.strip():
                    record['error_classification'] = 'visible_text_empty'
        except BaseException as error:
            record.update(status='failed', error_type=type(error).__name__,
                          error_classification=('timeout' if isinstance(error, (TimeoutError, httpx.TimeoutException))
                                                else 'transport_failure' if isinstance(error, httpx.TransportError)
                                                else 'local_or_response_validation_failure'))
        finally:
            if token is not None and not settled:
                budget.settle(token, None if sent else '0')
                record['usage_status'] = 'unknown_after_dispatch' if sent else 'not_dispatched'
            record.update(ended_at=utc_now(), elapsed_seconds=time.monotonic() - started, dispatched=sent)
            write_json(output / 'receipt.json', record, exclusive=True, key=key)
            write_json(output / 'budget-summary.json', budget.summary(), exclusive=True)
        return {'status': record['status'], 'selection': alias, 'http_status': record['http_status'],
                'estimated_usd': record['estimated_usd'], 'budget': budget.summary()}


async def self_test():
    """Offline scripted transport checks, not a model-quality evaluation."""
    calls = []
    synthetic_key = 'offline-secret-example'
    old_key = os.environ.get(PROVIDER_KEYS['aihubmix'])
    def key_loader(*args):
        os.environ[PROVIDER_KEYS['aihubmix']] = synthetic_key
    def response(request):
        calls.append(request)
        return httpx.Response(200, headers={'request-id': 'req_test'}, json={
            'id': 'msg_test', 'model': 'provider-claimed-model', 'stop_reason': 'end_turn',
            'usage': {'input_tokens': 100, 'output_tokens': 20, 'cache_read_input_tokens': 10},
            'content': [{'type': 'thinking', 'thinking': 'MUST_NOT_PERSIST', 'signature': 'MUST_NOT_PERSIST'},
                        {'type': 'text', 'text': 'Visible answer ' + synthetic_key}]})
    def factory(handler):
        def create(**kwargs):
            kwargs['transport'] = httpx.MockTransport(handler)
            return httpx.AsyncClient(**kwargs)
        return create
    def scaffold(base):
        base.mkdir()
        for name in DOCUMENTS[:-1]:
            (base / name).write_text('Explicit synthetic offline test\n', encoding='utf-8')
        write_json(base / 'pricing.json', {alias: {'model': 'synthetic-' + alias,
            'input_per_million': '5', 'output_per_million': '25', 'cache_read_per_million': '0.5',
            'source_url': 'https://example.invalid/offline-test', 'checked_date': '2026-10-07'} for alias in ALIASES})
        prepare(base)
    try:
        with tempfile.TemporaryDirectory(prefix='uteki-consult-offline-') as directory:
            base = Path(directory) / 'success'
            scaffold(base)
            success = await run('opus55', base, client_factory=factory(response), key_loader=key_loader)
            assert success['status'] == 'completed' and success['estimated_usd'] == '0.001005'
            assert (base / 'runs/opus55/answer.md').read_text() == 'Visible answer [REDACTED]'
            saved = ''.join(path.read_text() for path in (base / 'runs/opus55').glob('*') if path.is_file())
            assert synthetic_key not in saved and 'MUST_NOT_PERSIST' not in saved
            try:
                await run('opus55', base, client_factory=factory(response), key_loader=key_loader)
                raise AssertionError('Duplicate was not blocked')
            except FileExistsError:
                pass
            try:
                prepare(base)
                raise AssertionError('Reprepare was not blocked')
            except ValueError:
                pass
            timeout_base = Path(directory) / 'timeout'
            scaffold(timeout_base)
            def timeout(request):
                raise httpx.ReadTimeout('Do not persist this message ' + synthetic_key, request=request)
            failed = await run('opus55', timeout_base, client_factory=factory(timeout), key_loader=key_loader)
            assert failed['status'] == 'failed' and failed['budget']['unknown_requests'] == 1
            try:
                RunBudget(timeout_base / 'budget.sqlite', LIMIT).reserve('0.01')
                raise AssertionError('Unknown cost did not close budget')
            except BudgetExceeded:
                pass
            assert usage_cost({'input_tokens': 1, 'output_tokens': 1, 'cache_creation_input_tokens': 2},
                              prices(base / 'pricing.json')['opus55'])[0] is None
            assert usage_cost({}, prices(base / 'pricing.json')['opus55'])[0] is None
        return {'status': 'offline_self_test_passed', 'model_calls': 0,
                'checks': ['successful_receipt_and_cache_cost', 'hidden_content_omission', 'secret_redaction',
                           'duplicate_block', 'reprepare_block', 'timeout_unknown_cost_hold', 'unknown_cost_fail_closed']}
    finally:
        if old_key is None:
            os.environ.pop(PROVIDER_KEYS['aihubmix'], None)
        else:
            os.environ[PROVIDER_KEYS['aihubmix']] = old_key


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--prepare', action='store_true')
    mode.add_argument('--run', choices=ALIASES)
    mode.add_argument('--self-test', action='store_true')
    parser.add_argument('--source', action='append', default=[], type=Path,
                        help='Additional context-evidence source to hash; preparation only')
    args = parser.parse_args()
    try:
        if args.source and not args.prepare:
            raise ValueError('Source selection is only valid before freezing')
        result = (prepare(sources=args.source) if args.prepare else asyncio.run(self_test())
                  if args.self_test else asyncio.run(run(args.run)))
        print(json.dumps(result, ensure_ascii=False, allow_nan=False))
        return 0 if result['status'] in {'prepared', 'completed', 'offline_self_test_passed'} else 1
    except Exception as error:
        print(json.dumps({'status': 'stopped', 'error_type': type(error).__name__}, allow_nan=False))
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
